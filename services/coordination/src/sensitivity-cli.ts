// Writes the RPS/BROA sensitivity study to <output directory> as JSON plus a readable Markdown summary.
// Usage: node build/src/sensitivity-cli.js <output directory>. Deterministic: the same code writes identical files.
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { runSensitivityStudy } from "./sensitivity.js";

const outputDirectory = process.argv[2];
if (!outputDirectory) { console.error("Usage: sensitivity-cli <output directory>"); process.exit(2); }
const study = runSensitivityStudy();
const { rps, broa, surplusGrid, panelExample } = study.results;
const percent = (value: number) => `${value.toFixed(2)}%`;
const lines = [
  "# RPS and BROA sensitivity analysis",
  "",
  `${study.studyVersion} · SIMULATION_ONLY · ${study.approvalStatus}. Generated by \`services/coordination/src/sensitivity-cli.ts\`; do not edit by hand.`,
  `Seed ${study.seed}; ${study.generatedScenarios} generated scenarios per algorithm plus the manuscript's Table 7 (RPS) and Table 8 (BROA) scenarios.`,
  `Policies: RPS \`${study.rpsPolicyVersion}\`, BROA and surplus \`${study.broaPolicyVersion}\`. Result SHA-256 \`${study.resultSha256}\`.`,
  "",
  "One parameter changes at a time; weights are rescaled and renormalized to sum to 1. The production score functions are reused unchanged.",
  "These are synthetic scenarios. The analysis shows how stable the rankings are; it does not justify any value clinically. Approval stays open under RQ-05, RQ-06 and RQ-16.",
  "",
  "## RPS (baseline urgency 0.70, wait 0.30, wait cap 24 h)",
  "",
  "| Change | Urgency / wait weight | Critical always first | Top choice changed | Mean Kendall τ | Min τ | Table 7 order |",
  "|---|---|---|---:|---:|---:|---|",
  ...rps.map((row) => `| ${row.factor === null ? row.parameter : `urgency × ${row.factor}`} | ${row.weights.urgencyWeight.toFixed(4)} / ${row.weights.waitWeight.toFixed(4)} (cap ${row.weights.waitCapHours} h) | ${row.criticalAlwaysOutranksUrgent ? "Yes" : "**No**"} | ${percent(row.topChoiceChangedPercent)} | ${row.meanKendallTau.toFixed(4)} | ${row.minKendallTau.toFixed(4)} | ${row.table7Order.map((id) => id.replace("TRF_SIM_", "")).join(" > ")} |`),
  "",
  `A new Critical request always outranks an Urgent request at the wait cap only while ${study.results.criticalPrecedenceThreshold}.`,
  "",
  "## BROA (baseline urgency 0.50, shortage 0.3125, distance 0.1875)",
  "",
  "| Weight changed | Factor | Weights (U / S / D) | Top choice changed | Mean Kendall τ | Min τ | Table 8 order |",
  "|---|---:|---|---:|---:|---:|---|",
  ...broa.map((row) => `| ${row.parameter} | × ${row.factor} | ${Object.values(row.weights).map((value) => value.toFixed(4)).join(" / ")} | ${percent(row.topChoiceChangedPercent)} | ${row.meanKendallTau.toFixed(4)} | ${row.minKendallTau.toFixed(4)} | ${row.table8Order.map((id) => id.replace("INST_HOSPITAL_", "")).join(" > ")} |`),
  "",
  "## Distributable-surplus buffers (baseline allowance 2, reserve 10)",
  "",
  "`Surplus = max(0, ⌊eligible − forecast − allowance − reserve⌋)`. The gate opens when the surplus covers the requested quantity.",
  "",
  "| Allowance | Reserve | Gate open | Decision changed vs baseline | Table 8 source surplus (25 units, forecast 4.59) |",
  "|---:|---:|---:|---:|---:|",
  ...surplusGrid.map((row) => `| ${row.safetyAllowance} | ${row.minimumReserve} | ${percent(row.gateOpenPercent)} | ${percent(row.gateDecisionChangedPercent)} | ${row.table8SourceSurplus} |`),
  "",
  "### The panel's worked example (20 eligible units, 12-unit reserve)",
  "",
  "| Forecast | Allowance | Surplus |",
  "|---:|---:|---:|",
  ...panelExample.map((row) => `| ${row.pointForecast} | ${row.safetyAllowance} | ${row.surplus} |`),
  "",
  "With no forecast and no allowance the surplus is 20 − 12 = 8, as in the panel's example. The study's formula also subtracts the next-day forecast and a safety allowance.",
  "",
];
await mkdir(outputDirectory, { recursive: true });
await writeFile(join(outputDirectory, "RPS-BROA-SENSITIVITY.json"), `${JSON.stringify(study, null, 2)}\n`);
await writeFile(join(outputDirectory, "RPS-BROA-SENSITIVITY.md"), lines.join("\n"));
console.log(`Sensitivity study written: ${study.resultSha256}`);
